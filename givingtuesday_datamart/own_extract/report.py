"""The parity report: every measure of ``parity`` over the loaded batches, as markdown."""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from sqlalchemy import text

from givingtuesday_datamart.own_extract import extract, parity
from givingtuesday_datamart.own_extract.load import LOGICAL_NAME

_COLUMN_FIELDS = ["column", "n", "equal", "gt_only", "ours_only", "differ", "differ_case_space",
                  "agree_pct"]


def _md(df: pd.DataFrame) -> str:
    if df.empty:
        return "_none_\n"
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    rule = "|" + "|".join("---" for _ in df.columns) + "|"
    body = []
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if v is None or (isinstance(v, float) and pd.isna(v)):
                cells.append("")
            elif isinstance(v, (int,)) and not isinstance(v, bool):
                cells.append(f"{v:,}")
            else:
                cells.append(str(v))
        body.append("| " + " | ".join(cells) + " |")
    return "\n".join([head, rule, *body]) + "\n"


def loaded_batches(session) -> pd.DataFrame:
    """The latest successful load of each batch, with its stamps."""
    return pd.read_sql(text(
        f"""SELECT DISTINCT ON (source_url) split_part(source_version, '@', 1) AS batch,
                   source_manifest->'batch'->>'last_modified' AS last_modified,
                   left(source_manifest->'batch'->>'sha256', 12) AS zip_sha256,
                   left(source_manifest->>'concordance_sha256', 12) AS concordance_sha256,
                   (source_manifest->'rows'->>'returns_990')::int AS returns_990,
                   (source_manifest->'rows'->>'returns_990PF')::int AS returns_990pf,
                   (source_manifest->'rows'->>'returns_990EZ')::int AS returns_990ez,
                   (SELECT string_agg(substr(k, 9) || ' ' || v, ', ' ORDER BY k)
                    FROM jsonb_each_text(source_manifest->'rows') AS e(k, v)
                    WHERE k LIKE 'version_%') AS schema_versions,
                   finished_at
            FROM datamart_meta.ingest_runs
            WHERE logical_name = '{LOGICAL_NAME}' AND status = 'success'
            ORDER BY source_url, finished_at DESC"""), session.connection())


_FORMS = {"basic_fields": "990", "basic_fields_pf": "990-PF", "basic_fields_ez": "990-EZ"}


def run(session, out: Path, batch_ids: list[str] | None = None) -> str:
    """Write the report to ``out`` a section at a time, and return it.

    Each section is appended as soon as it is measured, so a run that stops
    keeps what it finished (the first full run held two and a half hours of
    results in memory and lost them). The quick checks of the newest schema
    versions come first; then each table, GT's table read once (``parity``).
    """
    concordance = extract.load()
    stamps = loaded_batches(session)
    session.commit()          # release ingest_runs before the long measures (a loader ALTERs it)
    if batch_ids:
        stamps = stamps[stamps["batch"].isin(batch_ids)]
    batch_ids = sorted(stamps["batch"])
    parity.prepare(session)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("")
    written: list[str] = []

    def emit(*parts: str) -> None:
        block = "\n".join(parts) + "\n"
        written.append(block)
        with out.open("a") as handle:
            handle.write(block)
        # A dropped temp table's files go only at commit: in one transaction the
        # 2026-10-23 runs kept every table's to the end (72 to 33 GB free).
        session.commit()
        parity.prepare(session)      # the next statement may get another pooled connection

    emit("# Our IRS extract against GivingTuesday's tables\n",
         "Generated by `python -m givingtuesday_datamart.own_extract parity`. GT's side is its",
         "staging rows under the same url (GT's own pattern, carried by our rows too); for the",
         "grant tables also the repaired `_current` relations.\n",
         "## Batches\n",
         _md(stamps.sort_values("batch")[["batch", "last_modified", "zip_sha256",
                                          "concordance_sha256", "returns_990", "returns_990pf",
                                          "returns_990ez", "schema_versions"]]))
    emit(schema_checks(session))

    cover, gaps, periods = [], [], []
    emit("## Tables\n")
    # Schedule O last: GT's is 21 GB, the biggest read by far.
    order = sorted(concordance.items(), key=lambda item: item[0] == "schedule_o")
    for table, mappings in order:
        cover.append(parity.coverage(session, table, batch_ids))
        gaps.append(parity.gap(session, table))
        section = [f"### {table}\n", _md(pd.DataFrame([cover[-1]])),
                   "What GT does not have:\n", _md(pd.DataFrame([gaps[-1]]))]
        if table in _FORMS:
            periods.append(parity.gap_by_period(session, _FORMS[table]))
        if table not in extract.GROUPS:
            cols = parity.columns(session, table, mappings)
            cols["agree_pct"] = (100 * cols["equal"] / cols["n"].clip(lower=1)).round(3)
            read = cols[cols["read"]]
            section += [f"{int((read['agree_pct'] == 100).sum())} of {len(read)} columns production "
                        f"reads agree on every return; all columns: "
                        f"{int((cols['agree_pct'] == 100).sum())} of {len(cols)}.\n",
                        "Read columns below 100%:\n",
                        _md(read[read["agree_pct"] < 100][_COLUMN_FIELDS])]
            rest = cols[~cols["read"] & (cols["agree_pct"] < 100)]
            if not rest.empty:
                section += ["Columns production does not read, below 100%:\n",
                            _md(rest[_COLUMN_FIELDS])]
        else:
            compared = [parity.rows(session, table, table)]
            if table in parity.CURRENT:
                compared.append(parity.rows(session, table, parity.CURRENT[table]))
            section += ["Returns by GT's row count against the return's group count:\n",
                        _md(parity.shapes(session)),
                        "Our rows with an identical row (columns production reads) under the same url:\n",
                        _md(pd.DataFrame(compared))]
        emit(*section)

    emit("## GT's blanked Schedule I rows (recipient name line 2), priced by ours\n",
         _md(pd.DataFrame([parity.schedule_i_line2(session)])))
    emit("## privategrants_current's repair rules, run over our paid rows\n",
         "Production's DDL with our rows as the source and our `basic_fields_pf` as the return",
         "table. `(none)` is a row kept as it is.\n", _md(parity.repair_rules(session)))
    by_period = pd.concat(periods, ignore_index=True)
    emit("## Summary: coverage\n", _md(pd.DataFrame(cover)),
         "## Summary: what GT does not have (all loaded batches)\n", _md(pd.DataFrame(gaps)),
         "Returns by the year the tax period ends (2019 on):\n",
         _md(by_period[by_period["period_ends"] >= "2019"]))
    return "".join(written)


EARLY_2026 = [f"2026_TEOS_XML_0{i}A" for i in range(1, 5)]          # GT released these
LATE_2026 = ["2026_TEOS_XML_05A", "2026_TEOS_XML_05B", "2026_TEOS_XML_06A",
             "2026_TEOS_XML_07A", "2026_TEOS_XML_08A", "2026_TEOS_XML_09A"]   # GT has none


def schema_checks(session) -> str:
    """Whether the concordance holds for the schema versions GT has not seen.

    Two measures. Parity on the returns of 2026 01A-04A filed under 2025v4.x,
    the only ones of that version GT holds. And, for 2026 05A-09A (GT has
    none of it; about 71% 2025v4.x), each column's fill rate beside 01A-04A's:
    a column filled there and empty here is the mark of a renamed element.
    """
    concordance = extract.load()
    parity.prepare(session)
    out = ["## The newest schema versions (2025v4.x and later)\n"]
    found = session.execute(text(
        "SELECT count(*) FROM irs_extract.returns WHERE return_version LIKE '2025v4%' "
        "AND _batch_id = ANY(:b)"), {"b": EARLY_2026}).scalar()
    out.append(f"Returns filed under 2025v4.x in 2026 01A-04A (GT holds them): {found:,}.\n")
    for table, mappings in concordance.items():
        if table in extract.GROUPS:
            continue
        parity.coverage(session, table, EARLY_2026, version_like="2025v4%")
        cols = parity.columns(session, table, mappings)
        cols["agree_pct"] = (100 * cols["equal"] / cols["n"].clip(lower=1)).round(3)
        read = cols[cols["read"]]
        out.append(f"### {table}, 2025v4.x returns only\n")
        out.append(f"{int((read['agree_pct'] == 100).sum())} of {len(read)} read columns agree on "
                   f"every one of {int(cols['n'].max()):,} returns.\n")
        out.append(_md(read[read["agree_pct"] < 100][_COLUMN_FIELDS]))
    out.append("### Columns filled in 2026 01A-04A and much less in 05A-09A\n")
    out.append("Older = 01A-04A, newer = 05A-09A. Listed when the older batches fill the column "
               "on at least 2% of rows and the newer on less than a quarter as many.\n")
    shifts = pd.concat([parity.fill_shift(session, t, m, LATE_2026, EARLY_2026)
                        for t, m in concordance.items()], ignore_index=True)
    flagged = shifts[(shifts["older_filled_pct"] >= 2)
                     & (shifts["newer_filled_pct"] < shifts["older_filled_pct"] / 4)]
    out.append(_md(flagged))
    return "\n".join(out)
